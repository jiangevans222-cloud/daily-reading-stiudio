import fs from 'node:fs';
import path from 'node:path';
import {root,read,validate,write} from './lib.mjs';
const list=validate();
const config=read('site.config.json');
for(const key of ['name','tagline','description'])if(typeof config[key]!=='string'||!config[key].trim()||config[key].length>200)throw Error('site.config.json: invalid '+key);
if(config.repositoryUrl&&!/^https:\/\/github\.com\/[a-zA-Z0-9_.-]+\/[a-zA-Z0-9_.-]+\/?$/.test(config.repositoryUrl))throw Error('repositoryUrl must be a GitHub repository URL');
write('dist/site-config.json',config);
write('dist/courses.json',{version:1,lessons:list});
fs.writeFileSync(path.join(root,'dist/lessons.js'),'/* Generated by npm run build; edit content/lessons instead. */\nwindow.SEED_LESSONS = '+JSON.stringify(list,null,2)+';\n');
console.log(`Built ${list.length} shared lessons into dist/`);
